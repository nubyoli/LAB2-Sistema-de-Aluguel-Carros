CREATE TABLE momentcar.usuarios (
 id VARCHAR(36) PRIMARY KEY, usuario VARCHAR(80) NOT NULL UNIQUE,
 senha VARCHAR(100) NOT NULL, nome VARCHAR(150) NOT NULL,
 perfil VARCHAR(10) NOT NULL CHECK (perfil IN ('CLIENTE','EMPRESA','BANCO'))
);
CREATE TABLE momentcar.clientes (
 id VARCHAR(36) PRIMARY KEY REFERENCES momentcar.usuarios(id),
 rg VARCHAR(30) NOT NULL UNIQUE, cpf VARCHAR(11) NOT NULL UNIQUE CHECK (LENGTH(cpf)=11),
 nome VARCHAR(150) NOT NULL, endereco VARCHAR(300) NOT NULL, profissao VARCHAR(100) NOT NULL
);
CREATE TABLE momentcar.empregos (
 cliente_id VARCHAR(36) NOT NULL REFERENCES momentcar.clientes(id) ON DELETE CASCADE,
 posicao INTEGER NOT NULL CHECK (posicao BETWEEN 1 AND 3), entidade VARCHAR(150) NOT NULL,
 rendimento DECIMAL(14,2) NOT NULL CHECK (rendimento>=0), PRIMARY KEY(cliente_id,posicao)
);
CREATE TABLE momentcar.automoveis (
 id VARCHAR(36) PRIMARY KEY, matricula VARCHAR(40) NOT NULL UNIQUE,
 ano INTEGER NOT NULL CHECK (ano BETWEEN 1886 AND 2100), marca VARCHAR(80) NOT NULL,
 modelo VARCHAR(100) NOT NULL, placa VARCHAR(7) NOT NULL UNIQUE,
 proprietario_id VARCHAR(36) NOT NULL REFERENCES momentcar.usuarios(id)
);
CREATE TABLE momentcar.pedidos (
 id VARCHAR(36) PRIMARY KEY, numero BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
 cliente_id VARCHAR(36) NOT NULL REFERENCES momentcar.clientes(id),
 agente_id VARCHAR(36) NOT NULL REFERENCES momentcar.usuarios(id),
 automovel_id VARCHAR(36) NOT NULL REFERENCES momentcar.automoveis(id),
 inicio DATE NOT NULL, fim DATE NOT NULL CHECK (fim>=inicio),
 tipo_contrato VARCHAR(10) NOT NULL CHECK (tipo_contrato IN ('CLIENTE','EMPRESA','BANCO')),
 banco_id VARCHAR(36) REFERENCES momentcar.usuarios(id),
 status VARCHAR(15) NOT NULL CHECK (status IN ('EM_ANALISE','APROVADO','REPROVADO','CANCELADO','CONTRATADO')),
 revisao INTEGER NOT NULL DEFAULT 1, criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX pedidos_cliente_idx ON momentcar.pedidos(cliente_id);
CREATE INDEX pedidos_agente_idx ON momentcar.pedidos(agente_id);
CREATE TABLE momentcar.avaliacoes (
 id VARCHAR(36) PRIMARY KEY, pedido_id VARCHAR(36) NOT NULL REFERENCES momentcar.pedidos(id),
 agente_id VARCHAR(36) NOT NULL REFERENCES momentcar.usuarios(id), revisao INTEGER NOT NULL,
 aprovado BOOLEAN NOT NULL, parecer VARCHAR(2000) NOT NULL,
 criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE momentcar.contratos (
 id VARCHAR(36) PRIMARY KEY, pedido_id VARCHAR(36) NOT NULL UNIQUE REFERENCES momentcar.pedidos(id),
 agente_id VARCHAR(36) NOT NULL REFERENCES momentcar.usuarios(id),
 banco_id VARCHAR(36) REFERENCES momentcar.usuarios(id), credito_referencia VARCHAR(100),
 criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CHECK ((banco_id IS NULL AND credito_referencia IS NULL) OR (banco_id IS NOT NULL AND credito_referencia IS NOT NULL)),
 UNIQUE (banco_id,credito_referencia)
);
